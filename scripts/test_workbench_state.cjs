const assert = require("node:assert/strict");
const state = require("../beginner_frontend/static/workflow-state.js");
const job = (id, metadata) => ({ id, status: "success", width: 1280, height: 720, fps: 24,
  media: [{ kind: "video", filename: `${id}.mp4`, type: "output", metadata }] });
const flow = state.create();
const first = state.begin(flow, "a", { stepId: "draft" });
assert.equal(state.complete(flow, job("a"), first), true);
const upscale = state.begin(flow, "up", { stepId: "upscale", source: flow.outputs.draft, scale: 2 });
assert.equal(state.complete(flow, job("up"), upscale), true);
assert.equal(flow.outputs.upscale.width, 2560);
assert.equal(state.complete(flow, job("up"), upscale), false, "completion is idempotent");
const second = state.begin(flow, "b", { stepId: "draft" });
assert.equal(flow.outputs.upscale, undefined, "new shot clears derived selections, not files");
assert.equal(state.complete(flow, job("b"), second), true);
const rife = state.begin(flow, "r", { stepId: "rife", source: flow.outputs.draft, multiplier: 4 });
assert.equal(state.complete(flow, job("r"), rife), true);
assert.equal(flow.outputs.rife.fps, 96, "uses submitted multiplier, not a later UI value");
assert.equal(state.sourceFor(flow, "deflicker").filename, "b.mp4");
assert.equal(state.sourceFor(flow, "upscale").filename, "r.mp4");
const stale = state.begin(flow, "stale", { stepId: "upscale", source: flow.outputs.rife });
state.adopt(flow, { filename: "chosen.mp4", width: 640, height: 360, fps: 30 });
assert.equal(state.complete(flow, job("stale"), stale), false, "late job cannot replace an explicit source");
const detached = state.begin(flow, "late-ack", { stepId: "draft", expectedRevision: 0 });
assert.equal(state.complete(flow, job("late-ack"), detached), false);
assert.equal(flow.outputs.draft.filename, "chosen.mp4");
const measured = state.begin(flow, "measured", { stepId: "upscale", source: flow.outputs.draft, scale: 2 });
state.complete(flow, job("measured", { width: 1920, height: 1080, fps: 29.97 }), measured);
assert.equal(flow.outputs.upscale.height, 1080, "measured output wins over estimates");
assert.equal(flow.outputs.upscale.fps, 29.97);
assert.equal(state.trustedApiUrl("https://untrusted.example/api/test", "http://localhost:7860"), false);
assert.equal(state.trustedApiUrl("/api/jobs", "http://localhost:7860"), true);
assert.equal(state.trustedApiUrl("https://server.example/api/jobs", "http://localhost:7860", "https://server.example"), true);
console.log("PASS workflow state: lineage, invalidation, duplicate events, snapshots, metadata, trusted origins");
