def profile_by_id(profile_id: str | None) -> dict[str, Any] | None:
    return INSTALL_PROFILES.get((profile_id or "").strip())


def catalog_generation_target(item: dict[str, Any] | None) -> str:
    item = item or {}
    support = str(item.get("platform_support") or "manual")
    modes = item.get("workflow_modes") or {}
    has_native_mode = any(str(modes.get(step) or "").strip() for step in NATIVE_WORKFLOW_STEPS)
    if support == "native" and has_native_mode:
        return "native"
    if support == "cloud_api" and has_native_mode:
        return "cloud_api"
    if support == "official_workflow":
        return "comfy_template"
    return "catalog_only"


def model_catalog_payload() -> dict[str, Any]:
    assets_by_id = {str(asset.get("id") or ""): asset for asset in MODEL_ASSETS}
    items: list[dict[str, Any]] = []
    for source in MODEL_CATALOG:
        item = dict(source)
        profile_id = str(item.get("default_install_profile") or "manual")
        profile = INSTALL_PROFILES.get(profile_id, INSTALL_PROFILES["manual"])
        profile_asset_ids = [str(asset_id) for asset_id in profile.get("asset_ids") or []]
        core_asset_ids = [asset_id for asset_id in profile_asset_ids if asset_id not in POST_ASSET_IDS]
        profile_assets = [assets_by_id[asset_id] for asset_id in profile_asset_ids if asset_id in assets_by_id]
        core_assets = [assets_by_id[asset_id] for asset_id in core_asset_ids if asset_id in assets_by_id]
        profile_expected_bytes = sum(int(asset.get("bytes") or 0) for asset in profile_assets)
        core_expected_bytes = sum(int(asset.get("bytes") or 0) for asset in core_assets)
        core_node_ids = [
            str(node_id)
            for node_id in (profile.get("custom_node_ids") or [])
            if str(node_id) not in OPTIONAL_POST_NODE_IDS
        ]
        generation_target = catalog_generation_target(item)
        item["install_profile"] = profile_id
        item["install_profile_label"] = profile["label"]
        item["one_click_install"] = bool(profile.get("installable"))
        item["external_requirement"] = str(profile.get("external_requirement") or "")
        item["required_comfy_version"] = str(profile.get("required_comfy_version") or "")
        item["generation_target"] = generation_target
        item["generation_target_label"] = GENERATION_TARGET_LABELS.get(generation_target, GENERATION_TARGET_LABELS["catalog_only"])
        item["can_generate_here"] = generation_target in {"native", "cloud_api"}
        item["install_asset_count"] = len(core_assets)
        item["install_custom_node_count"] = len(core_node_ids)
        item["install_expected_bytes"] = core_expected_bytes
        item["install_expected_gb"] = round(core_expected_bytes / 1024**3, 2)
        item["install_full_asset_count"] = len(profile_assets)
        item["install_full_expected_gb"] = round(profile_expected_bytes / 1024**3, 2)
        workflow_modes = {
            str(step): str(mode)
            for step, mode in (item.get("workflow_modes") or {}).items()
            if str(mode).strip()
        }
        mode_capabilities = [video_params.mode_capabilities(mode) for mode in dict.fromkeys(workflow_modes.values())]
        item["capabilities"] = {
            "text_to_video": any(capability["text_to_video"] for capability in mode_capabilities),
            "image_to_video": any(capability["image_to_video"] for capability in mode_capabilities),
            "last_frame": any(capability["last_frame"] for capability in mode_capabilities),
            "native_audio": any(capability["native_audio"] for capability in mode_capabilities),
            "fixed_fps": next((capability["fixed_fps"] for capability in mode_capabilities if capability["fixed_fps"]), None),
            "engines": list(dict.fromkeys(capability["engine"] for capability in mode_capabilities)),
        }
        item["capability_labels"] = list(
            dict.fromkeys(
                label
                for mode in workflow_modes.values()
                for label in video_params.capability_labels(mode)
            )
        )
        items.append(item)

    return {
        "items": items,
        "families": sorted({str(item["family"]) for item in items}),
        "quantizations": sorted({str(item["quantization"]) for item in items}),
        "statuses": sorted({str(item["status"]) for item in items}),
        "source_presets": DOWNLOAD_SOURCE_PRESETS,
        "install_profiles": INSTALL_PROFILES,
        "updated_at": CATALOG_UPDATED_AT,
    }
